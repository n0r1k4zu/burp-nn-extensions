def _leading_number(comment):
    match = _LEADING_NUMBER_RE.match(comment or '')
    return match.group(1) if match else None


def _append_tag(comment, tag):
    marker = u'[%s]' % tag
    if marker in (comment or ''):
        return comment or u''
    return ((comment or u'').rstrip() + (u' ' if comment else u'') + marker)


def _prepend_tags(comment, tags):
    """Statistics2のタグを既存Commentの先頭へ、順序を保って挿入する。"""
    prefix = u' '.join(u'[%s]' % tag for tag in tags if tag)
    text = (comment or u'').strip()
    return prefix + (u' ' + text if prefix and text else text)


def group_names(comment):
    """Return sorted, de-duplicated group names from explicit group tags."""
    names = []
    for match in _GROUP_TAG_RE.findall(_comment_text(comment)):
        name = next((value for value in match if value), u'').strip()
        if name:
            names.append(name)
    return sorted(set(names))


def group_display(comment):
    return u', '.join(group_names(comment))


def annotate_analysis(records, add_class_tags=False, add_aggregation_tags=False,
                     clear_comments_first=False, color_targets=False, color_name='gray'):
    """Apply explicitly requested History annotations; return update counts."""
    updated = colored = 0
    original_numbers = dict((record['packet_no'], _leading_number(record['item'].getComment() or u''))
                            for record in records)
    for record in records:
        old = record['item'].getComment() or u''
        comment = u'' if clear_comments_first else old
        if add_class_tags:
            comment = _append_tag(comment, record['class'])
        if add_aggregation_tags and record['agg_role'] == u'target':
            representative = record['agg_rep']
            rep_number = original_numbers.get(representative['packet_no']) if representative else None
            # A representative can be outside the selected export set and
            # therefore have no leading [number].  Never lose the destination
            # in that case: History Packet No is stable for the current view
            # and makes the aggregation relationship immediately traceable.
            tag = (u'集約対象_集約先No%s' % rep_number if rep_number else
                   (u'集約対象_集約先PacketNo%s' % representative['packet_no']
                    if representative else u'集約対象'))
            comment = _append_tag(comment, tag)
        if comment != old:
            record['item'].setComment(comment)
            updated += 1
        if color_targets and record['agg_role'] == u'target':
            record['item'].setHighlight(color_name)
            colored += 1
    return updated, colored


def annotate_analysis_v2(records, add_dimension_tags=True, add_aggregation_tags=False,
                        clear_comments_first=False, color_targets=False, color_name='gray'):
    """Statistics2用注釈。3軸タグと集約タグを既存Commentの先頭へ追加する。"""
    updated = colored = 0
    original_numbers = dict((record['packet_no'], _leading_number(_comment_text(record['item'].getComment() or u'')))
                            for record in records)
    for record in records:
        old = _comment_text(record['item'].getComment() or u'')
        comment = u'' if clear_comments_first else _strip_statistics2_dimension_tags(old)
        tags = []
        if add_dimension_tags:
            tags.extend((u'Protocol=%s' % (record.get('protocol') or u'Other'),
                         u'Traffic Class=%s' % (record.get('traffic_class') or record.get('class') or API),
                         u'Category=%s' % (record.get('category') or u'Unknown')))
        if add_aggregation_tags and record['agg_role'] == u'target':
            representative = record['agg_rep']
            rep_number = original_numbers.get(representative['packet_no']) if representative else None
            tags.append(u'集約対象_集約先No%s' % rep_number if rep_number else
                        (u'集約対象_集約先PacketNo%s' % representative['packet_no']
                         if representative else u'集約対象'))
        comment = _prepend_tags(comment, tags) if tags else comment
        if comment != old:
            record['item'].setComment(comment)
            updated += 1
        if color_targets and record['agg_role'] == u'target':
            record['item'].setHighlight(color_name)
            colored += 1
    return updated, colored


def _strip_statistics2_dimension_tags(comment):
    """Statistics2自身が生成した3軸タグだけを差し替え前に除去する。"""
    labels = (u'trafficclass=', u'category=', u'protocol=')
    out = []
    cursor = 0
    while cursor < len(comment):
        start = comment.find(u'[', cursor)
        if start == -1:
            out.append(comment[cursor:])
            break
        end = comment.find(u']', start + 1)
        if end == -1:
            out.append(comment[cursor:])
            break
        label = comment[start + 1:end]
        compact = u''.join(label.strip().split()).lower()
        if any(compact.startswith(prefix) for prefix in labels):
            out.append(comment[cursor:start])
        else:
            out.append(comment[cursor:end + 1])
        cursor = end + 1
    return u''.join(out).strip()


def clear_analysis_annotations(callbacks, start_packet_no=None, end_packet_no=None):
    """Remove only tags generated by Statistics from History comments.

    User numbering (`[0001]`), groups (`[group="..."]`) and unrelated
    bracket annotations remain untouched.
    """
    changed = packet_no = 0
    for item in callbacks.getProxyHistory():
        packet_no += 1
        if start_packet_no is not None and packet_no < start_packet_no:
            continue
        if end_packet_no is not None and packet_no > end_packet_no:
            break
        # ``getComment()`` can be a Java String, unicode, or Jython's raw
        # byte-string.  Comparing a Unicode ``new`` value to the latter asks
        # Jython to ASCII-decode Japanese tag bytes and can silently leave a
        # comment behind (or fail the background operation). Normalize before
        # both substitution *and* comparison.
        old = _comment_text(item.getComment() or u'')
        new = _strip_statistics_tags(old)
        # Retain the regular-expression pass only for unusual historic
        # whitespace spellings that pre-date the current tag format.
        new = _STATISTICS_TAG_RE.sub(u'', new)
        # Removing adjacent tags can leave several spaces before an existing
        # user comment.  Collapse only horizontal whitespace; line breaks in
        # a deliberately multi-line Comment are preserved.
        new = re.sub(r'[ \t]{2,}', u' ', new).strip()
        if new != old:
            item.setComment(new)
            changed += 1
    return changed


def number_all(callbacks, start_number, digits):
    """Prefix every current History comment with a zero-padded sequence."""
    changed = 0
    number = start_number
    for item in callbacks.getProxyHistory():
        old = item.getComment() or u''
        rest = _LEADING_NUMBER_RE.sub(u'', old, count=1)
        item.setComment((u'[%0*d] ' % (digits, number)) + rest)
        number += 1
        changed += 1
    return changed


def number_selected(messages, start_number=1, digits=4):
    """Apply the standard leading-number format to selected History items.

    This is the selected-packet counterpart of ``number_all``.  Existing
    leading numbers are replaced rather than stacked; every other comment
    tag/value is preserved for the subsequent Statistics annotation step.
    """
    changed = 0
    number = start_number
    for item in messages:
        old = _comment_text(item.getComment() or u'')
        rest = _LEADING_NUMBER_RE.sub(u'', old).lstrip()
        new = (u'[%0*d]' % (digits, number)) + (u' ' + rest if rest else u'')
        if new != old:
            item.setComment(new)
            changed += 1
        number += 1
    return changed


