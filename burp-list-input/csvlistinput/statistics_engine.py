# deliberately enumerated: a broad "remove all [..]" rule would also destroy
# user numbering and [group="..."] metadata.
_STATISTICS_TAG_RE = re.compile(
    r'\[\s*(?:'
    r'Web画面|Web個別パーツ取得|'
    r'SPA[（(]画面[）)]|SPA[（(]画面更新[）)]|API|'
    r'Web\s*Screen|Web\s*Part|SPA\s*Screen|SPA\s*Update|'
    r'Aggregation\s*Target|'
    r'集約対象(?:\s*_?\s*集約先\s*(?:No)?[^\]\r\n]+)?|'
    r'mytools\s*:\s*statistics\s*:\s*(?:class|aggregation)\s*=\s*[^\]\r\n]+'
    r')\s*\]\s*', re.IGNORECASE)
_STATISTICS_EXACT_TAGS = (
    u'[Web画面]', u'[Web個別パーツ取得]', u'[SPA（画面）]', u'[SPA（画面更新）]', u'[API]',
    # Historical/manual tags often use ASCII parentheses instead of the
    # full-width form emitted by the current UI.
    u'[SPA(画面)]', u'[SPA(画面更新)]',
    u'[集約対象]',
)
_STATISTICS_LABELS = set(tag[1:-1] for tag in _STATISTICS_EXACT_TAGS if tag != u'[集約対象]')


def _is_statistics_label(label):
    """True only for a bracket label owned by Statistics.

    This deliberately recognizes every ``集約対象...`` suffix generated by
    Statistics, including an arbitrary representative Number.  Groups and
    numbering have different labels and are never considered Statistics.
    """
    compact = u''.join((label or u'').strip().split())
    if compact in _STATISTICS_LABELS:
        return True
    lowered = compact.lower()
    return (compact.startswith(u'集約対象') or lowered in (
        u'webscreen', u'webpart', u'spascreen', u'spaupdate', u'aggregationtarget') or
        lowered.startswith(u'mytools:statistics:') or
        lowered.startswith(u'trafficclass=') or lowered.startswith(u'category=') or
        lowered.startswith(u'protocol='))


def _strip_statistics_tags(comment):
    """Remove Statistics-owned [tags] without relying on Java regex Unicode.

    Burp's Jython bridge can expose comments as Java-backed strings.  A small
    literal bracket scanner is more predictable than a non-ASCII regex there
    and accepts all representative-number variations.
    """
    out = []
    cursor = 0
    length = len(comment)
    while cursor < length:
        start = comment.find(u'[', cursor)
        if start == -1:
            out.append(comment[cursor:])
            break
        end = comment.find(u']', start + 1)
        if end == -1:
            out.append(comment[cursor:])
            break
        label = comment[start + 1:end]
        if _is_statistics_label(label):
            out.append(comment[cursor:start])
        else:
            out.append(comment[cursor:end + 1])
        cursor = end + 1
    return u''.join(out)


def _comment_text(comment):
    """Normalize Burp/Jython Java strings and byte comments to Unicode."""
    if comment is None:
        return u''
    try:
        unicode
        is_jython = True
    except NameError:
        is_jython = False
    if is_jython:
        # Jython 2's ``str``/``bytes`` is raw byte-string space.  Decode it
        # explicitly before unicode() can attempt its implicit ASCII path.
        if isinstance(comment, str):
            try:
                return comment.decode('utf-8')
            except Exception:
                return comment.decode('latin-1')
    else:
        if isinstance(comment, bytes):
            try:
                return comment.decode('utf-8')
            except Exception:
                return comment.decode('latin-1')
    try:
        return unicode(comment)
    except NameError:
        return str(comment)
    except Exception:
        # Some Java-backed String proxies do not satisfy str/unicode in
        # Jython.  Their textual representation is still recoverable, but
        # must follow the same explicit byte decoding discipline.
        try:
            raw = str(comment)
            try:
                return raw.decode('utf-8')
            except Exception:
                return raw.decode('latin-1')
        except Exception:
            return u''


def _text(helpers, value):
    if value is None:
        return u''
    try:
        return helpers.bytesToString(value)
    except Exception:
        if isinstance(value, bytes):
            return value.decode('latin-1')
        return value


def _headers(text):
    return text.split('\r\n\r\n', 1)[0].split('\n')


def _header(headers, name):
    prefix = name.lower() + ':'
    for line in headers[1:]:
        if line.lower().startswith(prefix):
            return line.split(':', 1)[1].strip()
    return ''


def _request_parts(text):
    lines = _headers(text)
    first = lines[0].split() if lines else []
    method = first[0] if first else ''
    target = first[1] if len(first) > 1 else '/'
    path, _, query = target.partition('?')
    body = text.split('\r\n\r\n', 1)[1] if '\r\n\r\n' in text else ''
    return method, path, query, body, lines


def _short_descriptor(value):
    value = (value or '').split('://', 1)[-1]
    if '/ACTION$' in value:
        left, action = value.split('/ACTION$', 1)
        return '%s/%s' % (left.split('.')[-1].split('/')[-1], action)
    return value.split('.')[-1]


def _aura_key(path, body, headers):
    """Build the conservative SF-Helper-inspired aggregation key."""
    message = ''
    page_uri = ''
    for pair in body.split('&'):
        key, sep, value = pair.partition('=')
        if not sep:
            continue
        if key == 'message':
            message = unquote_plus(value)
        elif key == 'aura.pageURI':
            page_uri = unquote_plus(value)
    descriptors = []
    objects = []
    apex_calls = []
    def collect_objects(value, key=''):
        if isinstance(value, dict):
            for child_key, child_value in value.items():
                collect_objects(child_value, to_display_text(child_key))
        elif isinstance(value, list):
            for child_value in value:
                collect_objects(child_value, key)
        elif to_display_text(key).lower() in _OBJECT_KEYS and value:
            objects.append(to_display_text(value))
    try:
        actions = json.loads(message).get('actions', [])
        for action in actions:
            if isinstance(action, dict):
                descriptor = _short_descriptor(action.get('descriptor', ''))
                if descriptor:
                    descriptors.append(descriptor)
                params = action.get('params', {})
                collect_objects(params)
                if 'ApexActionController' in (action.get('descriptor', '') or '') and isinstance(params, dict):
                    apex_name = params.get('classname') or params.get('apexClass') or ''
                    apex_method = params.get('method') or params.get('methodName') or ''
                    if apex_name or apex_method:
                        apex_calls.append('%s.%s' % (apex_name, apex_method))
    except Exception:
        pass
    auth = 'auth' if _header(headers, 'Cookie') or _header(headers, 'Authorization') else 'guest'
    if descriptors:
        return 'AURA|%s|%s|obj=%s|apex=%s|%s|%s' % (
            path, ','.join(sorted(set(descriptors))), ','.join(sorted(set(objects))) or '-',
            ','.join(sorted(set(apex_calls))) or '-', page_uri, auth)
    # Component-resource requests without descriptors are safe to merge only
    # when their full relevant request content is identical.
    digest = hashlib.sha1((path + '\n' + body + '\n' + auth).encode('utf-8')).hexdigest()
    return 'AURA-CONTENT|%s' % digest


def classify_packet(path, request_body, response_text, response_mime=''):
    """Return one of the five documented class labels, in precedence order."""
    lowered_path = (path or '').lower()
    lowered_body = (request_body or '').lower()
    response_lower = (response_text or '').lower()
    mime = (response_mime or '').lower()
    if 'auraanalytic' in lowered_path:
        return API
    if any(marker in lowered_path for marker in _AURA_MARKERS) or 'message=' in lowered_body or 'aura.context=' in lowered_body:
        return SPA_UPDATE
    ext = lowered_path.rsplit('.', 1)[-1] if '.' in lowered_path.rsplit('/', 1)[-1] else ''
    if ext in _STATIC_EXTS or any(marker in mime for marker in _STATIC_MIME):
        return WEB_PART
    if 'html' in mime or '<html' in response_lower:
        return SPA_SCREEN if any(marker in response_lower for marker in _SPA_HTML_MARKERS) else WEB_SCREEN
    return API


def analyze_history(callbacks, helpers, start_packet_no=None, end_packet_no=None, cancel_check=None):
    """Analyze inclusive one-based History bounds and return packet records."""
    records = []
    packet_no = 0
    for item in callbacks.getProxyHistory():
        packet_no += 1
        if cancel_check and cancel_check():
            break
        if start_packet_no is not None and packet_no < start_packet_no:
            continue
        if end_packet_no is not None and packet_no > end_packet_no:
            break
        request = _text(helpers, item.getRequest())
        response = _text(helpers, item.getResponse())
        method, path, query, body, request_headers = _request_parts(request)
        response_headers = _headers(response)
        response_mime = _header(response_headers, 'Content-Type')
        cls = classify_packet(path, body, response, response_mime)
        records.append({'packet_no': packet_no, 'item': item, 'class': cls, 'method': method,
                        'path': path, 'query': query, 'body': body, 'headers': request_headers,
                        'agg_key': _aura_key(path, body, request_headers) if cls == SPA_UPDATE else None,
                        'agg_role': u'single', 'agg_rep': None})
    _assign_aggregation(records)
    return records


def _assign_aggregation(records):
    """Mark first/subsequent packets of adjacent same-key Aura runs."""
    current = []
    current_key = None
    def finish(run):
        if len(run) <= 1:
            return
        representative = run[0]
        representative['agg_role'] = u'representative'
        representative['agg_rep'] = representative
        for record in run[1:]:
            record['agg_role'] = u'target'
            record['agg_rep'] = representative
    for record in records:
        if record['class'] != SPA_UPDATE:
            continue
        if current and record['agg_key'] == current_key:
            current.append(record)
        else:
            finish(current)
            current = [record]
            current_key = record['agg_key']
    finish(current)


def summary_rows(records):
    rows = []
    for label in CLASS_ORDER:
        total = len([record for record in records if record['class'] == label])
        reduced = len([record for record in records
                       if record['class'] == label and record['agg_role'] != u'target'])
        rows.append({'class': label, 'including_aggregated': total,
                     'excluding_aggregated': reduced, 'definition': CLASS_DEFINITIONS[label]})
    return rows


def _v2_origin_category(path, body):
    """Statistics2用の5分類。通信から確定できないものは安全側でUnknown。"""
    lowered_path = (path or u'').lower()
    if lowered_path.startswith(u'/services/apexrest/'):
        return u'ApexREST'
    if (lowered_path.startswith(u'/services/data/') or lowered_path.startswith(u'/services/connect/') or
            lowered_path.startswith(u'/services/async/') or lowered_path.startswith(u'/services/soap/')):
        return u'SalesforceREST'
    if u'message=' not in (body or u'').lower():
        return u'Unknown'
    message = u''
    for pair in (body or u'').split(u'&'):
        key, separator, value = pair.partition(u'=')
        if separator and key == u'message':
            message = unquote_plus(value)
            break
    try:
        actions = json.loads(message).get('actions', [])
    except Exception:
        actions = []
    categories = set()
    for action in actions:
        if not isinstance(action, dict):
            continue
        descriptor = to_display_text(action.get('descriptor', u''))
        scheme, separator, controller = descriptor.partition(u'://')
        if not separator:
            continue
        lowered_scheme = scheme.lower()
        lowered_controller = controller.lower()
        if lowered_scheme == u'apex':
            categories.add(u'Apexカスタム')
        elif lowered_scheme in (u'aura', u'servicecomponent'):
            if lowered_controller.endswith(u'apexactioncontroller/action$execute'):
                params = action.get('params') or {}
                class_name = to_display_text(params.get('classname') or params.get('apexClass') or
                                              params.get('className') or u'')
                if class_name:
                    categories.add(u'Apexカスタム')
                else:
                    categories.add(u'Unknown')
            else:
                categories.add(u'Salesforce標準')
    if len(categories) == 1:
        return next(iter(categories))
    return u'Unknown'


def _v2_protocol(path, body, response, response_mime, traffic_class):
    lowered_path = (path or u'').lower()
    lowered_body = (body or u'').lower()
    lowered_response = (response or u'').lower()
    mime = (response_mime or u'').lower()
    if traffic_class == SPA_UPDATE:
        return u'Aura'
    if u'graphql' in lowered_path or u'"query"' in lowered_body or u'query{' in lowered_body:
        return u'GraphQL'
    if u'/ui-api/' in lowered_path or u'/uiapi/' in lowered_path:
        return u'UI API'
    if (lowered_path.startswith(u'/services/') or lowered_path.startswith(u'/api/') or
            u'/rest/' in lowered_path or u'json' in mime or u'json' in lowered_body):
        return u'REST'
    if any(lowered_path.endswith(u'.' + extension) for extension in _STATIC_EXTS):
        return u'File'
    if u'html' in mime or u'<html' in lowered_response:
        return u'Web'
    return u'Other'


def analyze_history_v2(callbacks, helpers, start_packet_no=None, end_packet_no=None, cancel_check=None):
    """Statisticsの集約規則を保ったままTraffic Class/Category/Protocolを付与する。"""
    records = analyze_history(callbacks, helpers, start_packet_no, end_packet_no, cancel_check)
    for record in records:
        response = _text(helpers, record['item'].getResponse())
        response_mime = _header(_headers(response), 'Content-Type')
        record['traffic_class'] = record['class']
        record['category'] = _v2_origin_category(record['path'], record['body'])
        record['protocol'] = _v2_protocol(record['path'], record['body'], response,
                                          response_mime, record['traffic_class'])
    return records


def summary_rows_v2(records):
    """Traffic Class × Category × Protocol単位で、集約前後の件数を返す。"""
    grouped = {}
    for record in records:
        traffic_class = record.get('traffic_class') or record.get('class') or API
        key = (traffic_class, record.get('category') or u'Unknown', record.get('protocol') or u'Other')
        current = grouped.setdefault(key, {'traffic_class': traffic_class, 'category': key[1],
                                           'protocol': key[2], 'including_aggregated': 0,
                                           'excluding_aggregated': 0,
                                           'definition': _v2_definition(traffic_class, key[1], key[2])})
        current['including_aggregated'] += 1
        if record.get('agg_role') != u'target':
            current['excluding_aggregated'] += 1
    return sorted(grouped.values(), key=lambda row: (
        CLASS_ORDER.index(row['traffic_class']) if row['traffic_class'] in CLASS_ORDER else len(CLASS_ORDER),
        row['category'], row['protocol']))


